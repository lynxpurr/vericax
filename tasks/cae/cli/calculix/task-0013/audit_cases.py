"""Audit cases for cae--cli--calculix--task-0013 (exact_match, L1-L5).

Each entry is (label, bash script, expectation). The harness runs the first
script as the ground-truth source, so keep GOLD canonical.

The template below is the artifact an agent would deliver: one CalculiX deck of
a 200 x 100 x 2 mm plane-stress plate (40 x 20 CPS4, clamped at x = 0 in dofs
1-2) with three linear static steps - edge traction, body force, both - run once
with /usr/bin/ccx and summarised by its own .dat parser. PLATE_* environment
overrides let every negative stay ONE solver run: _run(env=..., after=...)
prefixes the generator and appends a post-run edit. Never concatenate two runs,
the second overwrites the first.

Hand estimate for the gold (2026-11-28; closed forms for a uniform uniaxial
stress state, far from the clamp):
  step 1  ux1 = sigma*L/E = 100*200/210000 = 0.095238 mm;
          clamp reaction -100 MPa * 100 mm * 2 mm = -20000 N
  step 2  ux(x) = -(rho g)(2Lx - x^2)/(2E), so ux2 = -(rho g) L^2/(2E)
          = -10*200/(2*210000) = -0.004762 mm; clamp reaction +2000 N
  step 3  ux3 = ux1 + ux2 (linear superposition); 0.090476 mm from the closed forms
The gold must agree with these within the verifier's nets. An independent
plane-stress FE solve of the prescribed mesh (numpy, not CalculiX) gives
ux1 = 0.094638, ux2 = -0.004702 and ux3 = 0.089936 mm: 0.63 % and 1.25 % below
the closed forms, because the clamp also blocks the lateral contraction, and
ux3 = ux1 + ux2 to 1e-16.

uy1 is NOT -nu*sigma*L/E = -0.028571 mm as first assumed. It is the mean uy of
the 21 FREE nodes, and it vanishes: the plate, the clamp and all three loads are
symmetric about y = 50, so the lateral contraction is antisymmetric (uy = 0 at
MIDFREE, about -nu*sigma*H/(2E) = -0.007143 mm at the top corner of the free
edge and +0.007143 mm at the bottom corner). The verifier tests |uy1| against
zero. A non-zero lateral observable would need a different definition.

Sign conventions come from real CalculiX 2.21 output found on this machine: RF
at a constrained node is the constraint force, opposite to the applied load
(+80 N at the root of a cantilever carrying -80 N at its tip; -21030 N at the
fixed face of a stretched block), and "*Dload: set, GRAV, g, gx, gy, gz" loads
along (gx, gy, gz). Not verifiable offline: whether RF under a body force
includes the 25 N share of the clamped nodes themselves (the verifier accepts
2000 N and 1975 N), whether CalculiX normalises a non-unit GRAV direction (the
gold uses the unit vector), and the run time.
"""

